import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Cell } from '../src/essays/cells.js';
import { mergeResolutions, parseReconciliation, reconcile, renderReconciliation, type CsvRow } from '../src/essays/reconcile.js';
import { readCsv } from '../src/migration/read-csv.js';
import { loadRegistry } from '../src/registry/load.js';

/*
 * `npm run essay:reconcile -- <legacy clone>` (spec 009, contracts/review-tooling.md): compares the anchor
 * essay's cell file with the legacy attestation CSV and writes the report, keeping the resolutions the author
 * already wrote. The clone is an argument and is never copied into this repository.
 */
const REPORT = 'docs/review/pit-cells-reconciliation.md';
const [clone] = process.argv.slice(2).filter((a) => a !== '--');
const fail = (message: string): never => {
  console.error(`essay:reconcile: ${message}`);
  process.exit(2);
};
if (!clone) fail('give the path of the legacy clone');
const csvFile = path.join(clone as string, 'data/dacia/attestations.csv');
if (!existsSync(csvFile)) fail(`${csvFile} does not exist`);

const { records } = await loadRegistry('.');
const essay = records.find((r) => r.family === 'essay' && r.slug === 'dacia-lapidarium');
if (!essay) fail('the essay dacia-lapidarium is not in the registry yet');
const cellsFile = essay!.file.replace(/\.yaml$/, '.cells.json');
if (!existsSync(cellsFile)) fail(`${cellsFile} does not exist yet: it is written when the pits are ported`);

const cells = JSON.parse(readFileSync(cellsFile, 'utf8')) as Cell[];
const csv = readCsv(readFileSync(csvFile, 'utf8'), csvFile) as unknown as CsvRow[];
const previous = existsSync(REPORT) ? parseReconciliation(readFileSync(REPORT, 'utf8')) : [];
const rows = mergeResolutions(reconcile(cells, csv), previous);
writeFileSync(REPORT, `# Anchor essay: the pit cells against the legacy attestations\n\nSpec 009 (FR-011). The essay's table is the source of truth; each row below is a difference for the author to resolve in the last two columns. Regenerated by \`npm run essay:reconcile\`, which keeps what is written there.\n\n${renderReconciliation(rows)}`);
const open = rows.filter((r) => r.difference !== 'none' && r.resolution === '').length;
console.log(`essay:reconcile: ${rows.length} rows written to ${REPORT}; ${open} differences without a resolution`);
