import { ImportError } from './context.js';
import { outcomeOf, successorOf, type InventoryEntry } from './inventory.js';
import type { RegistryRecord } from '../registry/types.js';

/*
 * The rule file for the archive project (spec 008 FR-017, contracts/redirect-inventory.md): one 301
 * rule per inventory entry that moved, in Cloudflare `_redirects` syntax with the new site's absolute
 * address. The command never pushes anywhere; the editor applies the file to the archive project by
 * pull request and signs `redirect_switched` (ADR 0010). An inventory that disagrees with the registry
 * (an essay published since it was built) is refused, so a rule can never be silently missing.
 */
const NEW_SITE = 'https://terra-chartarum.org';

export function archiveRedirects(inventory: readonly InventoryEntry[], records: readonly RegistryRecord[], meta: { snapshot: string; commit: string }): string {
  const successor = successorOf(records);
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const entry of inventory) {
    if (seen.has(entry.path)) throw new ImportError(`the inventory lists ${entry.path} twice`);
    seen.add(entry.path);
    const now = outcomeOf(entry.path, entry.kind, successor);
    if (now.outcome !== entry.outcome) throw new ImportError(`migration/redirect-inventory.json is out of date for ${entry.path} (the registry now says ${now.outcome}): run registry inventory again`);
    if (entry.outcome !== 'rule' || now.outcome !== 'rule') continue;
    if (entry.to !== now.to) throw new ImportError(`the rule for ${entry.path} points at ${entry.to}, which is not a page of the new site (the registry has ${now.to})`);
    lines.push(`${entry.path} ${NEW_SITE}${entry.to} 301`);
  }
  lines.sort((a, b) => ((a.split(' ')[0] as string) < (b.split(' ')[0] as string) ? -1 : 1));
  return [
    '# Redirects for the archive project (terra-chartarum.pages.dev). Generated by `registry archive-redirects`; do not edit by hand.',
    `# Snapshot ${meta.snapshot.slice(0, 7)}, registry commit ${meta.commit.slice(0, 7)}. Everything not listed is served by the archive where it is.`,
    '#',
    ...lines,
    '',
  ].join('\n');
}
